create_map_byvar <- function(path, 
                             varnam, 
                             labelnam,
                             longnam,
                             do_aggregate = FALSE, 
                             fact = 2, 
                             maps_only = FALSE,
                             colorscale = "bamako",
                             breaks = NULL,
                             legend_breaks = NULL,
                             units = "",
                             xaxis_ridgeplot = paste(longnam, units),
                             ...
){
  
  source(here::here("R/global_map_style.R"))
  # Select by NetCDF variable name; terra reads coordinate order directly.
  rasta <- terra::rast(path)[[varnam]]
  rasta_lo <- if (do_aggregate) terra::aggregate(rasta, fact = fact, fun = "mean") else rasta
  if (is.null(breaks)) {
    breaks <- scales::pretty_breaks(n = 10)(as.numeric(terra::global(rasta_lo, range, na.rm = TRUE)[1, ]))
  }
  colours <- khroma::colour(colorscale, reverse = TRUE)(length(breaks) - 1)
  if (is.null(legend_breaks)) legend_breaks <- breaks
  gg <- global_map_continuous(rasta_lo, colours, breaks, xaxis_ridgeplot, legend_breaks)
  save_global_map(gg, here::here(paste0("book/images/map_", labelnam)))
  if (maps_only) return(invisible(gg))

  ## By biome ---------------
  # file generated by analysis/plot_map_biomes.R
  rasta_biomes <- terra::rast(here::here("data/biomes_raster_0.1deg.tif"))
  
  # regrid the rasta (raster object of variable of interest) to the grid of the biome raster
  rasta_biomes_lo <- terra::resample(rasta_biomes, rasta_lo, method = "near")
  
  df_biomes <- rasta_biomes_lo |> 
    as.data.frame(xy = TRUE) |> 
    as_tibble() 
  # mutate(x = as.integer(round(100 * x)),
  #        y = as.integer(round(100 * y)))
  
  df_raster <- rasta_lo |> 
    as.data.frame(xy = TRUE) |> 
    as_tibble() |> 
    # mutate(x = as.integer(round(100 * x)),
    #        y = as.integer(round(100 * y))) |> 
    select(x, y, layer = !!varnam)
  
  df_joined <- df_raster |> 
    left_join(
      df_biomes,
      by = c("x", "y")
    )
    
  # df_joined <- df_raster |> 
  #   slice(1:10) |> 
  #   left_join(
  #     df_biomes, 
  #     by = c("x", "y"),
  #     max_dist = 0.201, 
  #     method = "manhattan"
  #   )

  biome_exclude <- c("Rock and Ice", "Inland Water")
  
  gg <- df_joined |> 
    dplyr::filter(!(WWF_MHTNAM %in% biome_exclude)) |>
    mutate(WWF_MHTNAM = factor(WWF_MHTNAM, levels = c("Tundra",
                                                      "BorealForests/Taiga",
                                                      "Montane Grasslands and Shrublands",
                                                      "TemperateConiferForests",
                                                      "Temperate Broadleaf and Mixed Forests",
                                                      "Mediterranean Forests, Woodlands and Scrub",
                                                      "Temperate Grasslands, Savannas and Shrublands",
                                                      "Deserts and Xeric Shrublands",
                                                      "Flooded Grasslands and Savannas",
                                                      "Mangroves",
                                                      "Tropical and Subtropical Grasslands, Savannas and Shrublands",
                                                      "Tropical and Subtropical Coniferous Forests",
                                                      "Tropical and Subtropical Dry Broadleaf Forests",
                                                      "Tropical and Subtropical Moist Broadleaf Forests"))) |> 
    dplyr::filter(!is.na(WWF_MHTNAM)) |>
    ggplot(aes(x = layer, 
               y = WWF_MHTNAM)) +
    geom_density_ridges(
      jittered_points = FALSE, scale = .95, rel_min_height = .01, 
    ) +
    scale_y_discrete(expand = c(0, 0), name = "") +
    scale_x_continuous(expand = c(0, 0), name = xaxis_ridgeplot) +
    coord_cartesian(clip = "off")
  
  ggsave(here::here(paste0("book/images/map_", labelnam, "_biome.png")), plot = gg, width = 8, height = 5)
  ggsave(here::here(paste0("book/images/map_", labelnam, "_biome.pdf")), plot = gg, width = 8, height = 5)
  
}
